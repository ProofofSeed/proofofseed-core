//! Generates the secp256k1 fixed-base comb table as flash-resident const data for constrained provers.
//!
//! Computes the same per-window multiples that zkboo-ecc's `ComputedWindowTables` builds at run
//! time, in Montgomery limbs, and writes them to
//! `circuits/src/comb_table.rs`. The device then reconstructs them from flash instead of recomputing
//! them with native point arithmetic each pass, and because the values are identical the host
//! verifier (which keeps computing them) still matches byte-for-byte.
//!
//! Re-run if the curve or default window width changes:
//!     cargo run -p proofofseed-host --example gen_comb_table --release

use std::fs::File;
use std::io::{BufWriter, Write};

use zkboo_ecc::weierstrass::{ComputedWindowTables, Curve, WindowTables, DEFAULT_COMB_WINDOW_BITS};
use zkboo_ecc::secp256k1::Secp256k1PM;

fn main() {
    let w = DEFAULT_COMB_WINDOW_BITS;
    let width: usize = 64 * 4; // u64 × 4 = 256-bit scalar
    let num_windows = width.div_ceil(w);
    let mut tables = ComputedWindowTables::new(Secp256k1PM.g(), w);

    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../circuits/src/comb_table.rs");
    let mut out = BufWriter::new(File::create(path).expect("create comb_table.rs"));
    // The licence header goes into the generated file too: every source file in this
    // repository carries one, and a generated file that omits it drifts out of compliance
    // the moment it is regenerated.
    writeln!(out, "// SPDX-License-Identifier: LGPL-3.0-or-later").unwrap();
    writeln!(out, "//").unwrap();
    writeln!(out, "// @generated by `cargo run -p proofofseed-host --example gen_comb_table` — DO NOT EDIT.").unwrap();
    writeln!(out, "//").unwrap();
    writeln!(out, "// secp256k1 fixed-base comb tables, in Montgomery limbs (little-endian u64).").unwrap();
    writeln!(out, "// Each entry is the Jacobian [X, Y, Z] the run-time comb produces.").unwrap();
    writeln!(out, "//").unwrap();
    writeln!(out, "// Window k is COMB_TABLE[COMB_WINDOW_OFFSETS[k]..COMB_WINDOW_OFFSETS[k+1]]. The").unwrap();
    writeln!(out, "// offsets are emitted rather than derived, because how many entries a window holds").unwrap();
    writeln!(out, "// is a property of the comb the table is generated from: an implementation that").unwrap();
    writeln!(out, "// stores only odd multiples needs half as many as one that stores all of them, and").unwrap();
    writeln!(out, "// a reader computing the stride itself silently mis-slices when that changes.").unwrap();
    writeln!(out, "pub const COMB_WINDOW_BITS: usize = {w};").unwrap();

    // Collect first, so the offsets can be written ahead of the data.
    let mut windows: Vec<Vec<[[u64; 4]; 3]>> = Vec::new();
    for k in 0..num_windows {
        windows.push(
            tables
                .window(k)
                .iter()
                .map(|entry| {
                    core::array::from_fn(|c| {
                        let bytes = (*entry[c].inner()).to_le_bytes();
                        core::array::from_fn(|i| u64::from_le_bytes(bytes[i]))
                    })
                })
                .collect(),
        );
    }
    write!(out, "pub static COMB_WINDOW_OFFSETS: &[usize] = &[0").unwrap();
    let mut running = 0usize;
    for wnd in &windows {
        running += wnd.len();
        write!(out, ", {running}").unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out, "pub static COMB_TABLE: &[[[u64; 4]; 3]] = &[").unwrap();

    let mut count = 0usize;
    for wnd in &windows {
        for entry in wnd {
            write!(out, "    [").unwrap();
            for limbs in entry {
                write!(
                    out,
                    "[0x{:016x}, 0x{:016x}, 0x{:016x}, 0x{:016x}], ",
                    limbs[0], limbs[1], limbs[2], limbs[3]
                )
                .unwrap();
            }
            writeln!(out, "],").unwrap();
            count += 1;
        }
    }

    writeln!(out, "];").unwrap();
    out.flush().unwrap();
    println!("wrote {count} entries ({} bytes data) to {path}", count * 96);
}
